def profile_for(industry_name: str, prospect_theme: str | None = None) -> IndustryProfile:
    text = f"{industry_name or ''} {prospect_theme or ''}"
    matches = [profile for profile in PROFILES if any(keyword in text for keyword in profile.keywords)]
    if not matches:
        return DEFAULT_PROFILE
    return max(matches, key=lambda item: max((len(k) for k in item.keywords if k in text), default=0))


def profile_dict(industry_name: str, prospect_theme: str | None = None) -> dict:
    p = profile_for(industry_name, prospect_theme)
    return {
        "profile": p.name,
        "valuation_focus": list(p.valuation_focus),
        "operating_focus": list(p.operating_focus),
        "balance_sheet_focus": list(p.balance_sheet_focus),
        "report_focus": list(p.report_focus),
    }
